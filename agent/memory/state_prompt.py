"""
agent/memory/state_prompt.py

State 更新的专用 Prompt（与客服 Prompt 分开管理）。
State 定位：用户事实条目库 —— 一个 ≤200 字的压缩文本库，每行一条独立事实/约束。
每轮单独一次 LLM 调用，对旧库做增/删/改，输出新的条目库。
"""

STATE_UPDATE_PROMPT = """
你将收到三部分内容：
1. 当前用户条目库：已有的用户事实条目（每行一条，形如「- 约束/事实」）。
2. 本轮事件：用户说了什么、AI 回复了什么。
3. 本轮工具调用：
   - 工具与参数：AI 实际调用的工具、填写的参数。
   - 执行结果（result）：工具真实返回的数据（可能为空，表示本轮没有可对照的真实结果）。

定位说明：
当前用户条目库是一个「压缩文本库」——每一行是一条独立的用户事实或约束，
如「- 预算：≤5000元」「- 排除：游戏本」「- 想买：笔记本电脑」。
每条互不粘连，方便逐条增删改，也方便装不下时按重要性淘汰。

任务：对照「本轮事件」与「执行结果」，对该条目库做一次增/删/改，输出更新后的新库。

逐条处理规则：
- 未变化的信息：原样保留对应行。
- 被修改：用户改口（预算、品类、偏好等变更）→ 用新值替换那一行，不得残留旧行。
- 被取消：用户明确放弃某项约束 → 删除对应行。
- 被新增：本轮出现的新需求/新约束 → 新增一行。
- 否定表达：用户说「不要」「排除」「除了」「别推荐」等 → 记为排除条目
  （如「- 排除：联想」），与正向偏好同等重要。
- 执行结果能佐证的约束可放心写入；执行结果与对话内容矛盾时，以真实结果为准修正。

补充规则：
1. 改口是最高优先级更新信号：必须覆盖旧值，不得保留互相矛盾的旧条目。
2. 用户新增需求（如换品类询问键盘）同样必须新增条目。
3. 只记录用户侧的**需求、偏好、预算、约束、决策进度**等事实。
4. 不要记录 AI 回复里的商品介绍与参数描述（屏幕尺寸、处理器、存储等——
   这些在对话记录里已有，无需进入持久条目库）。

输出要求：
- 每行一条，换行分隔，格式统一为「- 内容」，无编号、无嵌套、无多余解释。
- 总长度控制在 200 个中文字以内；装不下时按重要性淘汰或合并低优条目，不要拦腰截断某一行。
- 本轮没有新增用户信息时，也要完整保留原有条目，不要清空。
- 只输出条目库文本，不要任何解释或前缀。
"""


def get_state_update_prompt():
    """
    返回 State 更新的专用 Prompt。
    """
    return STATE_UPDATE_PROMPT
